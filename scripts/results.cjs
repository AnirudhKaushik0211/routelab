#!/usr/bin/env node
'use strict';
// Results generator (SPEC 7.5): docs/results.json, docs/RESULTS.md and the README results block.
//   node scripts/results.cjs [--check]
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const R = require('../js/routelab.js');

const ROOT = path.resolve(__dirname, '..');
const MARK_START = '<!-- results:start -->';
const MARK_END = '<!-- results:end -->';
const F = R.memo.format;
const MT = R.metrics;

function sha256(text) { return crypto.createHash('sha256').update(text, 'utf8').digest('hex'); }

function runSet(id, seedSet) {
  const runner = R.createRunner(R.getScenario(id), { scenarioId: id, seeds: seedSet.seeds, seedStart: seedSet.seedStart });
  while (!runner.isDone()) runner.step();
  return { res: runner.result(), runs: runner.runs(), config: runner.config() };
}

// buildResultsSet({ only }) -> { obj, json, md, block }
function buildResultsSet(opts) {
  const only = opts && opts.only;
  const scenarios = [];
  for (const s of R.scenarios) {
    if (only && only.indexOf(s.id) < 0) continue;
    const a = runSet(s.id, R.RESULTS_SEEDS);
    const b = runSet(s.id, R.ROBUST_SEEDS);
    const gw = a.config.gateways.map((g) => g.id);
    const def = R.scenariosData.byId[s.id];
    scenarios.push({
      id: s.id, title: s.title, configHash: a.res.configHash, focus: a.res.focus, summary: a.res.summary, status: a.res.status,
      paired: a.res.paired, focusSummary: a.res.focusSummary,
      expectations: { results: a.res.expectations, robust: b.res.expectations },
      headlines: def.headlines.map((h) => {
        const x = MT.headline(h, a.runs, a.config.focus, gw);
        return { text: x.text, mean: MT.round6(x.mean), ciLow: x.ciLow === null ? null : MT.round6(x.ciLow), ciHigh: x.ciHigh === null ? null : MT.round6(x.ciHigh) };
      })
    });
  }
  const obj = { schema: 'routelab.results-set.v1', version: R.VERSION,
    seedSets: { results: { seedStart: 101, seeds: 30 }, robust: { seedStart: 1, seeds: 20 } }, scenarios: scenarios };
  const json = JSON.stringify(obj, null, 2) + '\n';
  return { obj: obj, json: json, md: renderMd(obj), block: renderBlock(obj) };
}

function heldCount(list) { return list.filter((e) => e.held === true).length; }

function cellStat(stat, fmt, fmtNum) {
  if (!stat || stat.mean === null) return 'n/a';
  if (stat.ciLow === null) return fmt(stat.mean);
  return fmt(stat.mean) + ' (' + fmtNum(stat.ciLow) + ' to ' + fmtNum(stat.ciHigh) + ')';
}

function table(head, rows) {
  const L = ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|'];
  rows.forEach((r) => L.push('| ' + r.join(' | ') + ' |'));
  return L.join('\n');
}

function expectCell(row, e) {
  if (e.held === null) return 'SKIP';
  const tag = e.held ? 'PASS' : 'FAIL';
  if (e.value === null) return tag;
  if (row.op === 'exactlyEqual' || row.op === 'exactlyValue') return tag + ' (' + e.value + ' seeds)';
  return tag + ' (' + MT.formatObserved(row, e.value) + ')';
}

function renderMd(obj) {
  const L = [];
  L.push('# RouteLab results');
  L.push('');
  L.push('Generated by `npm run results` from RouteLab ' + obj.version + '. Seeds 101-130 (30). Synthetic data and illustrative assumptions; these numbers show how the strategies behave under the model in docs/MODEL.md, not real-world success rates. Not financial advice.');
  L.push('');
  L.push('How to read this: each cell is the mean across seeds with its 95% t-interval. Paired differences compare each strategy with static priority on the same traffic, seed by seed. pp = percentage points.');
  obj.scenarios.forEach((sc) => {
    const def = R.scenariosData.byId[sc.id];
    const pols = Object.keys(sc.summary);
    const base = Object.keys(sc.summary).filter((p) => !sc.paired[p])[0];
    L.push('');
    L.push('## ' + sc.title + ' (`' + sc.id + '`)');
    L.push('');
    L.push(def.story);
    L.push('');
    L.push('Changes from the base: ' + def.changes + '.');
    L.push('');
    L.push('Expected outcome: ' + def.expectationText);
    L.push('');
    L.push(table(['Strategy', 'Order SR', 'First-attempt SR', 'Cost per success', 'Effective fee rate', 'Time to success p95', 'Drop-off', 'Regret per 1,000'],
      pols.map((p) => {
        const s = sc.summary[p];
        return [R.POLICY_LABELS[p], cellStat(s.orderSr, F.pct, F.pctNum), cellStat(s.firstSr, F.pct, F.pctNum), cellStat(s.costPerSuccess, F.rs, F.rsNum),
          cellStat(s.feeRatePct, F.two, (x) => x.toFixed(2)), cellStat(s.ttsP95, F.sec, F.secNum), cellStat(s.dropRate, F.pct, F.pctNum), cellStat(s.regretPer1000, F.one, F.one)];
      })));
    L.push('');
    L.push('Paired difference from ' + R.POLICY_LABELS[base] + ':');
    L.push('');
    L.push(table(['Strategy', 'Order SR (pp)', 'First-attempt SR (pp)', 'Cost per success (Rs)', 'Regret per 1,000'],
      pols.filter((p) => p !== base).map((p) => {
        const d = sc.paired[p];
        return [R.POLICY_LABELS[p], R.memo.pairedCell(d.orderSr, F.pp), R.memo.pairedCell(d.firstSr, F.pp), R.memo.pairedCell(d.costPerSuccess, F.rsDiff), R.memo.pairedCell(d.regretPer1000, F.oneDiff)];
      })));
    if (sc.focus) {
      const f0 = sc.focus;
      L.push('');
      L.push('During ' + MT.windowLabel([f0.start, f0.end]) + ':');
      L.push('');
      const cfg = R.getScenario(sc.id);
      const perMethod = sc.id === 'collect-degradation' || cfg.events.some((e) => e.methods.length > 0);
      const gws = Object.keys(sc.focusSummary[pols[0]].share);
      const showShare = sc.id === 'steady' || sc.id === 'cold-start';
      const head = ['Strategy', 'Order SR', 'First-attempt SR'];
      if (perMethod) R.METHODS.forEach((m) => head.push('Order SR, ' + R.METHOD_LABELS[m]));
      if (showShare) gws.forEach((g) => head.push('Share of first attempts, Gateway ' + g));
      L.push(table(head, pols.map((p) => {
        const f = sc.focusSummary[p];
        const row = [R.POLICY_LABELS[p], cellStat(f.orderSr, F.pct, F.pctNum), cellStat(f.firstSr, F.pct, F.pctNum)];
        if (perMethod) R.METHODS.forEach((m) => row.push(cellStat(f.orderSrByMethod[m], F.pct, F.pctNum)));
        if (showShare) gws.forEach((g) => row.push(cellStat(f.share[g], F.pct, F.pctNum)));
        return row;
      })));
    }
    L.push('');
    L.push('How transactions ended (share of all transactions):');
    L.push('');
    L.push(table(['Strategy'].concat(R.REASONS.map((r) => R.REASON_LABELS[r])), pols.map((p) =>
      [R.POLICY_LABELS[p]].concat(R.REASONS.map((r) => cellStat(sc.status[p][r], F.pct, F.pctNum))))));
    L.push('');
    L.push('Expectation checks (fixed before measurement):');
    L.push('');
    L.push(table(['Id', 'Check', 'Seeds 101-130', 'Seeds 1-20'], def.expectations.map((row, i) => {
      const a = sc.expectations.results[i];
      const b = sc.expectations.robust[i];
      return [row.id, a.text, expectCell(row, a), expectCell(row, b)];
    })));
  });
  L.push('');
  L.push('Reproduce: `npm run results`; check: `npm run results -- --check`.');
  return L.join('\n') + '\n';
}

function renderBlock(obj) {
  const rows = obj.scenarios.map((sc) => {
    const def = R.scenariosData.byId[sc.id];
    const hl = sc.headlines.map((h) => h.text).join('<br>');
    const a = sc.expectations.results;
    const b = sc.expectations.robust;
    return [sc.title, def.story, hl, heldCount(a) + '/' + a.length + ' (seeds 101-130), ' + heldCount(b) + '/' + b.length + ' (seeds 1-20)'];
  });
  return table(['Scenario', 'What happens', 'Headline on seeds 101-130', 'Expectations held'], rows) + '\n';
}

function splice(readme, block) {
  const a = readme.indexOf(MARK_START);
  const b = readme.indexOf(MARK_END);
  if (a < 0 || b < 0 || b < a) return null;
  return readme.slice(0, a + MARK_START.length) + '\n' + block + readme.slice(b);
}

function readmeBlockOf(readme) {
  const a = readme.indexOf(MARK_START);
  const b = readme.indexOf(MARK_END);
  if (a < 0 || b < 0 || b < a) return null;
  return readme.slice(a + MARK_START.length + 1, b);
}

function notHeld(set) {
  const out = [];
  set.obj.scenarios.forEach((sc) => {
    ['results', 'robust'].forEach((k) => sc.expectations[k].forEach((e) => { if (e.held !== true) out.push(sc.id + ' ' + k + ' ' + e.id + ': ' + e.detail); }));
  });
  return out;
}

function hashes(set) { return { json: sha256(set.json), md: sha256(set.md), block: sha256(set.block) }; }

function main() {
  const check = process.argv.indexOf('--check') >= 0;
  const bad = process.argv.slice(2).filter((a) => a !== '--check');
  if (bad.length) { console.error('Usage: node scripts/results.cjs [--check]'); return 2; }
  const jsonPath = path.join(ROOT, 'docs', 'results.json');
  const mdPath = path.join(ROOT, 'docs', 'RESULTS.md');
  const readmePath = path.join(ROOT, 'README.md');
  if (check) {
    const s1 = buildResultsSet();
    const s2 = buildResultsSet();
    const h1 = hashes(s1);
    const h2 = hashes(s2);
    let diff = null;
    for (const k of ['json', 'md', 'block']) if (!diff && h1[k] !== h2[k]) diff = 'two generations differ in ' + k;
    const disk = {
      json: fs.existsSync(jsonPath) ? fs.readFileSync(jsonPath, 'utf8') : null,
      md: fs.existsSync(mdPath) ? fs.readFileSync(mdPath, 'utf8') : null,
      readme: fs.existsSync(readmePath) ? fs.readFileSync(readmePath, 'utf8') : null
    };
    if (!diff && disk.json !== s1.json) diff = 'docs/results.json differs from the generated content';
    if (!diff && disk.md !== s1.md) diff = 'docs/RESULTS.md differs from the generated content';
    if (!diff && (disk.readme === null || readmeBlockOf(disk.readme) !== s1.block)) diff = 'the README results block differs from the generated content';
    console.log('results.json sha256 ' + h1.json);
    console.log('RESULTS.md   sha256 ' + h1.md);
    if (diff) { console.log('DIFFERENT: ' + diff); return 1; }
    console.log('IDENTICAL');
    return 0;
  }
  const set = buildResultsSet();
  if (!fs.existsSync(readmePath)) { console.error('README.md is missing.'); return 1; }
  const spliced = splice(fs.readFileSync(readmePath, 'utf8'), set.block);
  if (spliced === null) { console.error('README.md has no ' + MARK_START + ' / ' + MARK_END + ' markers.'); return 1; }
  fs.writeFileSync(jsonPath, set.json, 'utf8');
  fs.writeFileSync(mdPath, set.md, 'utf8');
  fs.writeFileSync(readmePath, spliced, 'utf8');
  const h = hashes(set);
  console.log('docs/results.json sha256 ' + h.json);
  console.log('docs/RESULTS.md   sha256 ' + h.md);
  const nh = notHeld(set);
  if (nh.length) { nh.forEach((x) => console.error('NOT HELD: ' + x)); return 1; }
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { buildResultsSet, renderMd, renderBlock, splice, readmeBlockOf, sha256, MARK_START, MARK_END };
