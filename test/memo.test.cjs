'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const R = require('../js/routelab.js');

const res = R.simulate(R.getScenario('peak-outage'), { scenarioId: 'peak-outage', seeds: 3, seedStart: 1 });
const custom = (() => { const c = R.getScenario('steady'); c.run.txnPerDay = 2000; return R.simulate(c, { seeds: 3 }); })();

test('CSV header, row count and focus rows', () => {
  const lines = R.toCsv(res).split('\n');
  assert.equal(lines[0], 'scenario,policy,metric,mean,ci_low,ci_high,sd,n');
  assert.equal(lines[lines.length - 1], '');
  const pol = res.policies.length;
  const keys = R.metrics.DAY_KEYS.length;
  const focusRows = pol * (2 + 4 + res.config.gateways.length);
  assert.equal(lines.length - 2, pol * keys + (pol - 1) * keys + focusRows);
  assert.ok(lines.some((l) => l.indexOf('thompson-minus-static,orderSr,') > 0));
  assert.ok(lines.some((l) => /^peak-outage,static,focus_share_A,/.test(l)));
  assert.ok(lines.some((l) => /^peak-outage,thompson,focus_orderSr_upi_collect,/.test(l)));
  assert.ok(!R.toCsv(res).includes('\r'));
});

test('JSON parses with schema and ends with a newline', () => {
  const t = R.toJson(res);
  assert.equal(JSON.parse(t).schema, 'routelab.results.v1');
  assert.ok(t.endsWith('}\n'));
});

test('memo sections, preset and custom Setup lines', () => {
  const m = R.buildMemo(res, { generatedOn: '2025-06-01' });
  assert.ok(m.startsWith('# Routing decision memo: Evening-peak outage on the best gateway\n'));
  for (const h of ['## Setup', '## Results (mean across seeds, 95% interval)', '## Compared with Static priority (paired by seed)', '## Reading', '## Caveats']) assert.ok(m.includes(h), h);
  assert.ok(m.includes('- Scenario: Evening-peak outage on the best gateway (peak-outage).'));
  assert.ok(m.includes('Generated by RouteLab 1.0.0 on 2025-06-01.'));
  assert.ok(m.includes('- Events: Gateway A, all methods, 19:30 for 45 min at 10% of normal SR, recovery 15 min.'));
  assert.ok(/- Expected for this scenario: .* On these seeds \d+ of 6 checks held\./.test(m));
  const c = R.buildMemo(custom, { generatedOn: '2025-06-01' });
  assert.ok(c.startsWith('# Routing decision memo: Custom settings\n'));
  assert.ok(c.includes('- Scenario: custom settings (not an unmodified preset).'));
  assert.ok(c.includes('- Custom settings: no documented expectation applies.'));
  assert.ok(m.includes('not financial advice') || m.includes('Not financial advice'));
});

test('Reading branches', () => {
  const hand = JSON.parse(JSON.stringify(res));
  const set = (id, sr, cost, ciLow) => {
    hand.summary[id].orderSr.mean = sr; hand.summary[id].costPerSuccess.mean = cost;
    if (hand.paired[id]) hand.paired[id].orderSr = { mean: 0.01, sd: 0.001, ciLow, ciHigh: 0.02, n: 3 };
  };
  for (const p of hand.policies) if (!p.reference) set(p.id, 0.9, 10, -0.01);
  set('thompson', 0.95, 12, 0.005);
  set('weighted', 0.9, 8, -0.01);
  let m = R.buildMemo(hand, { generatedOn: '2025-06-01' });
  assert.ok(/- Highest order SR: Thompson sampling \(95\.00%\)\. Its gain over Static priority is \+1\.00 pp \(95% CI \+0\.50 to \+2\.00\)\./.test(m), m);
  assert.ok(m.includes('- Lowest cost per success: Weighted split (Rs 8.00).'));
  assert.ok(m.includes('- Trade-off: Thompson sampling has 5.00 pp higher order SR and Rs 4.00 higher cost per success than Weighted split.'));
  set('thompson', 0.95, 12, -0.005);
  m = R.buildMemo(hand, { generatedOn: '2025-06-01' });
  assert.ok(m.includes('On these seeds it cannot be told apart from Static priority.'));
  set('thompson', 0.9, 12, 0.005); set('static', 0.97, 8, 0);
  hand.summary.static.orderSr.mean = 0.97; hand.summary.static.costPerSuccess.mean = 5;
  m = R.buildMemo(hand, { generatedOn: '2025-06-01' });
  assert.ok(m.includes('It is the baseline.'));
  assert.ok(m.includes('- The same strategy is best on both.'));
});

test('generatedOn is required', () => {
  assert.throws(() => R.buildMemo(res), TypeError);
  assert.throws(() => R.buildMemo(res, {}), TypeError);
  assert.throws(() => R.buildMemo(res, { generatedOn: '1 June 2025' }), TypeError);
});

test('memo.format helpers', () => {
  const f = R.memo.format;
  assert.equal(f.pct(0.9512), '95.12%');
  assert.equal(f.pp(0.0123), '+1.23');
  assert.equal(f.pp(-0.0123), '-1.23');
  assert.equal(f.rs(13.567), 'Rs 13.57');
  assert.equal(f.sec(12.34), '12.3 s');
  assert.equal(f.int(10000), '10,000');
  assert.equal(f.pct(null), 'n/a');
});
